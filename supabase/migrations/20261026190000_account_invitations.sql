BEGIN;

CREATE TABLE IF NOT EXISTS public.account_invitations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  invited_by BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
  token_hash CHAR(64) NOT NULL UNIQUE,
  linked_student_id BIGINT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  relationship VARCHAR(50) NULL,
  expires_at TIMESTAMPTZ NOT NULL,
  accepted_at TIMESTAMPTZ NULL,
  revoked_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_invitation_parent_link CHECK (
    (linked_student_id IS NULL AND relationship IS NULL)
    OR (linked_student_id IS NOT NULL AND relationship IS NOT NULL)
  ),
  CONSTRAINT chk_invitation_single_terminal_state CHECK (
    accepted_at IS NULL OR revoked_at IS NULL
  )
);

CREATE INDEX IF NOT EXISTS idx_account_invitations_user_created
  ON public.account_invitations (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_account_invitations_expiry
  ON public.account_invitations (expires_at)
  WHERE accepted_at IS NULL AND revoked_at IS NULL;

-- Invitation tokens are handled only by the server. Browser Supabase roles
-- must not be able to read tokens or mutate invitation lifecycle state.
ALTER TABLE public.account_invitations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.account_invitations FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.account_invitations_id_seq FROM anon, authenticated;

COMMIT;
