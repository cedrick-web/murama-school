BEGIN;

CREATE TABLE IF NOT EXISTS public.school_inquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(30) NULL,
  subject VARCHAR(200) NOT NULL,
  message TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'IN_PROGRESS', 'CLOSED')),
  handled_by BIGINT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_inquiry_handler FOREIGN KEY (handled_by) REFERENCES public.users(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_school_inquiries_status_created
  ON public.school_inquiries (status, created_at DESC);

ALTER TABLE public.school_inquiries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.school_inquiries FROM anon, authenticated;

DROP TRIGGER IF EXISTS set_updated_at ON public.school_inquiries;
CREATE TRIGGER set_updated_at
  BEFORE UPDATE ON public.school_inquiries
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

COMMIT;
