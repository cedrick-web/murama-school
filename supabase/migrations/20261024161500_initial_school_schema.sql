-- Supabase Data API hardening: all school tables are private unless an explicit
-- policy and grant is added later. Backend traffic connects through the
-- server-side PostgreSQL connection string and never exposes a secret to React.
DO $$
DECLARE table_name text;
BEGIN
  FOR table_name IN
    SELECT t.tablename FROM pg_catalog.pg_tables AS t WHERE t.schemaname = 'public'
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
  END LOOP;
END $$;

REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon, authenticated;

-- Preserve MySQL's ON UPDATE CURRENT_TIMESTAMP semantics.
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

DO $$
DECLARE target_table text;
BEGIN
  FOR target_table IN
    SELECT c.table_name FROM information_schema.columns AS c
    WHERE c.table_schema = 'public' AND c.column_name = 'updated_at'
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS set_updated_at ON public.%I', target_table);
    EXECUTE format('CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.set_updated_at()', target_table);
  END LOOP;
END $$;

