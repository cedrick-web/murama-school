INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'school-media',
  'school-media',
  TRUE,
  26214400,
  ARRAY['image/jpeg', 'image/png', 'image/webp', 'image/avif', 'video/mp4', 'video/webm']
)
ON CONFLICT (id) DO UPDATE SET
  public = EXCLUDED.public,
  file_size_limit = EXCLUDED.file_size_limit,
  allowed_mime_types = EXCLUDED.allowed_mime_types;

CREATE TABLE IF NOT EXISTS public.school_media_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  alt_text VARCHAR(300) NOT NULL DEFAULT '',
  description TEXT NULL,
  category VARCHAR(30) NOT NULL DEFAULT 'SCHOOL_LIFE',
  media_type VARCHAR(10) NOT NULL,
  object_path TEXT NOT NULL UNIQUE,
  public_url TEXT NOT NULL,
  mime_type VARCHAR(100) NOT NULL,
  size_bytes BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'UPLOADING',
  uploaded_by BIGINT NULL REFERENCES public.users(id) ON DELETE SET NULL,
  published_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_school_media_type CHECK (media_type IN ('IMAGE', 'VIDEO')),
  CONSTRAINT chk_school_media_category CHECK (category IN ('SCHOOL_LIFE', 'EVENT', 'CAMPUS', 'ANNOUNCEMENT', 'OTHER')),
  CONSTRAINT chk_school_media_status CHECK (status IN ('UPLOADING', 'READY', 'PUBLISHED', 'ARCHIVED')),
  CONSTRAINT chk_school_media_size CHECK (size_bytes > 0 AND size_bytes <= 26214400),
  CONSTRAINT chk_school_media_title CHECK (length(trim(title)) BETWEEN 1 AND 180),
  CONSTRAINT chk_school_media_image_alt CHECK (media_type <> 'IMAGE' OR length(trim(alt_text)) BETWEEN 1 AND 300)
);

CREATE INDEX IF NOT EXISTS idx_school_media_public_gallery
  ON public.school_media_items (status, published_at DESC, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_school_media_category
  ON public.school_media_items (category, status);

ALTER TABLE public.school_media_items ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.school_media_items FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.school_media_items_id_seq FROM anon, authenticated;

COMMIT;
