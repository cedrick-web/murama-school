BEGIN;

CREATE TABLE IF NOT EXISTS public.school_visit_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(254) NULL,
  phone VARCHAR(40) NULL,
  visitor_type VARCHAR(30) NOT NULL DEFAULT 'OTHER',
  preferred_date DATE NOT NULL,
  preferred_time TIME NULL,
  purpose TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'NEW',
  response_note TEXT NULL,
  handled_by BIGINT NULL REFERENCES public.users(id) ON DELETE SET NULL,
  handled_at TIMESTAMPTZ NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_school_visit_contact CHECK (email IS NOT NULL OR phone IS NOT NULL),
  CONSTRAINT chk_school_visit_type CHECK (visitor_type IN ('PARENT', 'STUDENT', 'PROSPECTIVE_PARENT', 'OTHER')),
  CONSTRAINT chk_school_visit_status CHECK (status IN ('NEW', 'CONTACTED', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
  CONSTRAINT chk_school_visit_purpose CHECK (length(trim(purpose)) BETWEEN 10 AND 3000)
);

CREATE INDEX IF NOT EXISTS idx_school_visit_requests_status_created
  ON public.school_visit_requests (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_school_visit_requests_preferred_date
  ON public.school_visit_requests (preferred_date, status);

ALTER TABLE public.school_visit_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.school_visit_requests FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.school_visit_requests_id_seq FROM anon, authenticated;

COMMIT;
